#!/usr/bin/env python3
"""Regenerate js/embedded-assets.js from the files in assets/.

The studio inlines three assets as base64 so it keeps working when index.html is
opened straight from disk (file://), where browsers block canvas pixel reads and
fetch() of local files:
  - the sample hero, so its colours can be sampled and its margins trimmed
  - Red Hat Display 700 and Playfair Display Italic 700, which are embedded in
    the exported Figma HTML so it renders correctly on any machine

Run after replacing any of those files:  python3 tools/build-embedded.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = {
    "sampleHero": ("assets/images/sample-hero.png", "data:image/png;base64,"),
    "redHat700": ("assets/fonts/red-hat-display-700.woff2", ""),
    "playfairItalic700": ("assets/fonts/playfair-display-italic-700.woff2", ""),
}

lines = [
    "// Generated by tools/build-embedded.py from the files in assets/. Do not edit by hand.",
    "const EMBED = {",
]
for key, (path, prefix) in ASSETS.items():
    data = base64.b64encode((ROOT / path).read_bytes()).decode("ascii")
    lines.append(f'  {key}: "{prefix}{data}",')
lines.append("};")
(ROOT / "js/embedded-assets.js").write_text("\n".join(lines) + "\n")
print("wrote js/embedded-assets.js")
